// استخراج مقادیر یکتا برای فیلترها
export const getFilterOptions = (hotels) => {
  // استخراج ستاره‌های یکتا
  const starOptions = [...new Set(hotels.map(h => h.stars))].sort((a, b) => b - a);
  
  // استخراج امکانات یکتا
  const amenityOptions = [...new Set(hotels.flatMap(h => h.amenities))].sort();
  
  // استخراج نوع وعده غذایی یکتا
  const mealOptions = [...new Set(hotels.flatMap(h => h.mealType))].sort();
  
  // استخراج نوع اقامت یکتا
  const accommodationOptions = [...new Set(hotels.map(h => h.accommodationType))].sort();

  return {
    stars: starOptions,
    amenities: amenityOptions,
    meals: mealOptions,
    accommodations: accommodationOptions
  };
};